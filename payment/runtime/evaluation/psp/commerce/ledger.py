SUPPORTED = {44, 45, 46}
TABLE = {44: "cod_returns", 45: "prior_tax_refunds", 46: "treasury_distributions"}
ZH = {
    44: "Fully collect cash collected on behalf and carrier shortfall., Simultaneously refund the original buyer based on actual return, And use the same net proceeds to complete replenishment; Compare carrier net offset payment and merchant direct refund. ",
    45: "Pay tax according to current actual tax collection responsibility and refund another historical tax overcharge; Separately use or retain same-territory credits actually generated by the refund and original prepayment credits.. ",
    46: "After fully reconstructing both account statements and eliminating internal transfers, Allocate and pay based on actual external receipts; Use the same restricted cash to compare early redemption charges, Supplier discounts and maturity windows. ",
}


def verify(w, c, base):
    n = c["number"]
    a = c["acceptance"]
    i = c["initial_world"]
    rid = a["reasoning_id"]
    owner = i["_customer_id"]
    r = w["xp_c_" + TABLE[n]][rid]
    r0 = i["xp_c_" + TABLE[n]][rid]
    checks = base(w, c)["checks"]
    j = [
        x
        for x in w.get("xp_journal", {}).values()
        if x.get("customer_id") == owner
        and x.get("record_type") == "cash_posting"
        and (x["id"] not in i.get("xp_journal", {}))
    ]

    def money(k):
        return sum((x["amount_minor"] for x in j if x["kind"] == k))

    def rows(t):
        return [x for x in w.get("xp_c_" + t, {}).values() if x.get("customer_id") == owner]

    def ck(key, ok, detail):
        checks.append(
            dict(
                name=f"c{n}_reasoning_{key}",
                passed=bool(ok),
                detail=detail,
                explanation={"check_zh": ZH[n], "rule_documents": [f"PX-C-R{n}", f"PX-C-{n}"]},
            )
        )

    if n == 44:
        refunds = rows("cod_buyer_refunds")
        paid = sum((x["amount_minor"] for x in refunds))
        ck(
            "refund",
            paid == r0["_refund_minor"]
            and all((x["order_id"] == r0["order_id"] for x in refunds))
            and (-money("carrier_buyer_return_offset") - money("cod_direct_buyer_refund") == paid),
            refunds,
        )
        ck(
            "replenishment",
            r.get("replenishment_paid_minor") == r0["replenishment_minor"]
            and -money("cod_replenishment") == r0["replenishment_minor"],
            r.get("replenishment_paid_minor"),
        )
    elif n == 45:
        checks = [x for x in checks if x["name"] != "c45_journal"]
        remits = rows("tax_remittances")
        new = sum((x.get("generated_refund_credit_minor", 0) for x in remits))
        old = sum((x.get("credit_minor", 0) for x in remits))
        tax = sum((x["amount_minor"] for x in remits))
        ck(
            "refund",
            -money("prior_tax_buyer_refund") == r0["refund_minor"]
            and r.get("recipient") == r0["original_recipient"],
            dict(amount=-money("prior_tax_buyer_refund"), recipient=r.get("recipient")),
        )
        ck(
            "credit",
            r.get("credit_received")
            and (
                r.get("credit_period") == "CARRY_FORWARD"
                and new == 0
                and (not r.get("credit_used_minor"))
                or (
                    r.get("credit_period") == "CURRENT"
                    and new == r0["refund_minor"] == r.get("credit_used_minor")
                    and (r.get("assigned_jurisdiction") == r0["_authority_jurisdiction"])
                )
            ),
            dict(new=new, period=r.get("credit_period")),
        )
        ck(
            "tax_cash",
            -money("sales_tax_remittance") + old + new == tax,
            dict(cash=-money("sales_tax_remittance"), original=old, generated=new, liability=tax),
        )
    else:
        paid = rows("treasury_disbursements")
        source = 2500 * r0["distribution_numerator"] // r0["distribution_denominator"]
        own = [x for x in paid if x["obligation"] == "OWNER"]
        supplier = [x for x in paid if x["obligation"] == "SUPPLIER"]
        discount = bool(supplier) and all(
            (
                x["supplier_terms"] == "early_discount"
                and x["minute"] <= r0["discount_until_minute"]
                for x in supplier
            )
        )
        due = r0["supplier_face_minor"] - (r0["supplier_discount_minor"] if discount else 0)
        ck(
            "owner",
            sum((x["amount_minor"] for x in own)) == source
            and all((x["minute"] <= r0["owner_deadline"] for x in own)),
            own,
        )
        ck(
            "supplier",
            sum((x["amount_minor"] for x in supplier)) == due
            and all((x["minute"] <= r0["supplier_deadline"] for x in supplier)),
            supplier,
        )
        ck(
            "fees",
            -money("treasury_redemption_fee") <= r0["redemption_fee_cap_minor"],
            -money("treasury_redemption_fee"),
        )
        ck(
            "held_cash",
            all(
                (
                    w["xp_accounts"][aid]["balance_minor"] >= hold
                    for (aid, hold) in r["hold_by_account"].items()
                )
            ),
            r["hold_by_account"],
        )
    return dict(success=all((x["passed"] for x in checks)), checks=checks)


def wrap(previous):
    return lambda w, c: (
        verify(w, c, previous)
        if c["number"] in SUPPORTED and c.get("reasoning_revision")
        else previous(w, c)
    )
